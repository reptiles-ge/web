import fs from "node:fs";
import path from "node:path";

import {
  getSchemaImageCrops,
  getUploadedOptimizedImages,
} from "../src/lib/optimizedImagesApi";

const outFile = path.join(
  process.cwd(),
  "src/data/optimizedImages.api.generated.ts",
);

async function main() {
  const [images, crops] = await Promise.all([
    getUploadedOptimizedImages(),
    getSchemaImageCrops(),
  ]);
  if (images === null) {
    console.warn(
      "The API has no /v1/images yet; writing an empty image catalog.",
    );
  }
  if (crops === null) {
    console.warn(
      "The API has no /v1/images/schema-crops yet; writing an empty crop catalog.",
    );
  }
  const source = `/* eslint-disable */
// Generated by scripts/compile-optimized-images.ts from the API — do not edit by hand.
import type { OptimizedImageEntry } from "../lib/optimizedImageSources";
import type { SchemaCrop } from "../lib/schemaCropTypes";

export const uploadedOptimizedImages: Record<string, OptimizedImageEntry> = ${JSON.stringify(images ?? {}, null, 2)};

export const uploadedSchemaImageCrops: Record<string, SchemaCrop[]> = ${JSON.stringify(crops ?? {}, null, 2)};
`;
  fs.writeFileSync(outFile, source, "utf8");
  console.log(
    `Compiled ${Object.keys(images ?? {}).length} optimized images and ${Object.keys(crops ?? {}).length} schema crop sets from the API → ${outFile}`,
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
