UPDATE species SET taxon_class = CASE taxon_order
    WHEN 'Accipitriformes' THEN 'Aves'
    WHEN 'Anseriformes' THEN 'Aves'
    WHEN 'Anura' THEN 'Amphibia'
    WHEN 'Araneae' THEN 'Arachnida'
    WHEN 'Artiodactyla' THEN 'Mammalia'
    WHEN 'Blattodea' THEN 'Insecta'
    WHEN 'Bucerotiformes' THEN 'Aves'
    WHEN 'Caprimulgiformes' THEN 'Aves'
    WHEN 'Carnivora' THEN 'Mammalia'
    WHEN 'Caudata' THEN 'Amphibia'
    WHEN 'Charadriiformes' THEN 'Aves'
    WHEN 'Ciconiiformes' THEN 'Aves'
    WHEN 'Columbiformes' THEN 'Aves'
    WHEN 'Cuculiformes' THEN 'Aves'
    WHEN 'Eulipotyphla' THEN 'Mammalia'
    WHEN 'Falconiformes' THEN 'Aves'
    WHEN 'Galliformes' THEN 'Aves'
    WHEN 'Gruiformes' THEN 'Aves'
    WHEN 'Hemiptera' THEN 'Insecta'
    WHEN 'Hymenoptera' THEN 'Insecta'
    WHEN 'Mantodea' THEN 'Insecta'
    WHEN 'Passeriformes' THEN 'Aves'
    WHEN 'Piciformes' THEN 'Aves'
    WHEN 'Rodentia' THEN 'Mammalia'
    WHEN 'Scorpiones' THEN 'Arachnida'
    WHEN 'Squamata' THEN 'Reptilia'
    WHEN 'Strigiformes' THEN 'Aves'
    WHEN 'Testudines' THEN 'Reptilia'
  END;

UPDATE species SET checklist_status_id = CASE
    WHEN id IN ('phoenicolacerta-laevis', 'trachemys-scripta') THEN 'introduced'
    WHEN id IN ('anguis-colchica', 'bufo-verrucosissimus', 'darevskia-adjarica', 'darevskia-alpina', 'darevskia-brauneri', 'darevskia-caucasica', 'darevskia-obscura', 'darevskia-pontica', 'dolichophis-caspius', 'dolichophis-schmidti', 'elaphe-urartica', 'hyla-orientalis', 'lacerta-media', 'lissotriton-lantzi', 'malpolon-insignitus', 'vipera-darevskii', 'vipera-dinniki', 'vipera-renardi') THEN 'candidate'
    ELSE 'confirmed'
  END
WHERE group_id IN ('amphibian', 'lizard', 'snake', 'turtle');

