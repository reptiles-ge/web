import fs from "node:fs";
import path from "node:path";

import { ANIMAL_GROUP_TO_HUB } from "../src/lib/groupHubs";
import { getSpeciesCatalog } from "../src/lib/speciesCatalogApi";
import { buildPublishedSlugMaps } from "../src/lib/speciesSlugRules";

const outFile = path.join(process.cwd(), "src/data/speciesSlugs.generated.ts");

const atlasMetaFile = path.join(
  process.cwd(),
  "src/data/speciesAtlasMeta.generated.ts",
);

async function main() {
  const catalog = await getSpeciesCatalog("ka");
  if (catalog.length === 0) {
    throw new Error("The species API returned no published species.");
  }
  if (catalog.some((item) => !Array.isArray(item.slugAliases))) {
    console.warn(
      "The species API returned no slugAliases, so former slugs will not redirect. Apply migrations 0021–0022 and deploy the API before the site.",
    );
  }
  const maps = buildPublishedSlugMaps(
    catalog.map((item) => ({
      hub: ANIMAL_GROUP_TO_HUB[item.group],
      id: item.id,
      slug: item.slug,
      slugAliases: item.slugAliases ?? [],
    })),
  );
  const atlasMetaById = Object.fromEntries(
    [...catalog]
      .sort((a, b) => a.id.localeCompare(b.id))
      .map((item) => [item.id, { group: item.group, habitats: item.habitats }]),
  );
  const atlasMetaSource = `/* eslint-disable */
// Generated by scripts/compile-species-slugs.ts from the species API — do not edit by hand.
import type { SpeciesAtlasMeta } from "./speciesAtlasMeta";

export const speciesAtlasMetaById: Record<string, SpeciesAtlasMeta> = ${JSON.stringify(atlasMetaById, null, 2)};
`;
  const source = `/* eslint-disable */
// Generated by scripts/compile-species-slugs.ts from the species API — do not edit by hand.
import type { GroupHubId } from "../lib/groupHubs";

export const speciesHubById: Record<string, GroupHubId> = ${JSON.stringify(maps.hubById, null, 2)};

export const kaSlugById: Record<string, string> = ${JSON.stringify(maps.kaSlugById, null, 2)};

export const idByAnySlug: Record<string, string> = ${JSON.stringify(maps.idByAnySlug, null, 2)};
`;
  fs.writeFileSync(outFile, source, "utf8");
  fs.writeFileSync(atlasMetaFile, atlasMetaSource, "utf8");
  console.log(
    `Compiled ${catalog.length} published slug rows from the API → ${outFile}`,
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
