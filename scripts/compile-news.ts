import fs from "node:fs";
import path from "node:path";

import type { NewsArticle } from "../src/data/newsTypes";

import { newsSlugs } from "../src/data/newsPublish";
import { optimizedImages } from "../src/data/optimizedImages.generated";
import { checkNewsHeroes, type NewsHeroInput } from "../src/lib/newsHeroImage";
import {
  newsArticleFromMdx,
  readNewsMdxFiles,
} from "../src/lib/newsMdxArticle";
import { newsSlugIssue } from "../src/lib/newsSlug";

const contentRoot = path.join(process.cwd(), "src/content/news");
const outFile = path.join(process.cwd(), "src/data/news.generated.ts");

const errors: string[] = [];
const heroes: NewsHeroInput[] = [];
const folders = fs
  .readdirSync(contentRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name);

for (const folder of folders) {
  if (!newsSlugs.includes(folder as (typeof newsSlugs)[number]))
    errors.push(`${folder}: folder is missing from newsSlugs`);
}

for (const slug of newsSlugs) {
  const issue = newsSlugIssue(slug);
  if (issue) errors.push(`${slug}: ${issue}`);
}

const articles: NewsArticle[] = [];
for (const slug of newsSlugs) {
  try {
    const result = newsArticleFromMdx(
      slug,
      readNewsMdxFiles(contentRoot, slug),
    );
    errors.push(...result.errors);
    if (!result.article) continue;
    articles.push(result.article);
    heroes.push({
      exception: result.heroImageException,
      image: result.article.image,
      publishedAt: result.article.publishedAt,
      slug,
    });
  } catch (error) {
    errors.push(`${slug}: ${(error as Error).message}`);
  }
}

const heroCheck = checkNewsHeroes(heroes, optimizedImages);
errors.push(...heroCheck.errors);
if (heroCheck.warnings.length > 0)
  console.warn(
    `News heroes not ready for Discover:\n${heroCheck.warnings.map((line) => `  ${line}`).join("\n")}`,
  );

if (errors.length > 0) {
  console.error(errors.join("\n"));
  process.exit(1);
}

fs.writeFileSync(
  outFile,
  `/* eslint-disable */\n// Generated by scripts/compile-news.ts — do not edit by hand.\nimport type { NewsArticle } from "./newsTypes";\n\nexport const NEWS_ARTICLES: readonly NewsArticle[] = ${JSON.stringify(articles, null, 2)};\n`,
);
console.log(
  `Compiled ${articles.length} news articles → ${path.relative(process.cwd(), outFile)}`,
);
