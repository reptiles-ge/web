export type DangerLevel = "Harmless" | "Moderate" | "High";

export type SpeciesStat = {
  label: string;
  value: string;
};

export type SpeciesFaq = {
  question: string;
  answer: string;
};

export type PhotoCredit = {
  photographer: string;
  url?: string;
};

export type GalleryImage = {
  src: string;
  credit?: PhotoCredit;
};

export type Species = {
  id: string;
  commonName: string;
  scientificName: string;
  genus: string;
  family: string;
  location: string;
  description: string;
  overview: string;
  habitat: string;
  diet: string;
  behavior: string;
  conservation: string;
  danger: DangerLevel;
  image: string;
  imageCredit?: PhotoCredit;
  mobileImage?: string;
  mobileImageCredit?: PhotoCredit;
  gallery: GalleryImage[];
  stats: SpeciesStat[];
  facts: string[];
  faq?: SpeciesFaq[];
};

export function gallerySrcs(gallery: GalleryImage[]): string[] {
  return gallery.map((item) => item.src);
}

export function resolvePhotoCredit(
  ...credits: Array<PhotoCredit | undefined>
): PhotoCredit | undefined {
  return credits.find(Boolean);
}

